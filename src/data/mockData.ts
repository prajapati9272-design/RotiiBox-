// Helper to generate the next 7 days of scheduled meals for an active subscription
export function generateScheduleForSubscription(
  currentHour: number = 9,
  currentMinute: number = 15
): DailyMealSchedule[] {
  const schedule: DailyMealSchedule[] = [];
  const today = new Date();

  const daysOfWeek = ['Sunday', 'Monday', 'Tuesday', 'Wednesday', 'Thursday', 'Friday', 'Saturday'];
  const monthNames = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];

  for (let i = 0; i < 7; i++) {
    const d = new Date(today);
    d.setDate(today.getDate() + i);

    const dateStr = d.toISOString().split('T')[0];
    const dayLabel = i === 0 ? 'Today' : i === 1 ? 'Tomorrow' : daysOfWeek[d.getDay()];
    const formattedDate = `${d.getDate()} ${monthNames[d.getMonth()]}`;

    // Lunch item
    // Cutoff is 10:30 AM
    // For today (i=0): past cutoff if simulated hour > 10 or (hour == 10 and min >= 30)
    const isTodayLunchPastCutoff = i === 0 ? (currentHour > 10 || (currentHour === 10 && currentMinute >= 30)) : false;

    schedule.push({
      date: dateStr,
      dayLabel: `${dayLabel} Lunch`,
      formattedDate,
      mealSlot: 'lunch',
      rotiCount: 4,
      rotiType: i === 2 ? 'multigrain' : i === 5 ? 'methi_thepla' : 'phulka_wheat',
      gheeApplied: i % 2 === 0,
      deliveryTimeSlot: '12:30 PM - 01:15 PM',
      status: isTodayLunchPastCutoff ? 'in_preparation' : 'scheduled',
      cutoffTime: '10:30 AM',
      isPastCutoff: isTodayLunchPastCutoff,
      specialInstructions: 'Piping hot in thermal sleeve',
    });

    // Dinner item
    // Cutoff is 06:30 PM (18:30)
    const isTodayDinnerPastCutoff = i === 0 ? (currentHour > 18 || (currentHour === 18 && currentMinute >= 30)) : false;

    schedule.push({
      date: dateStr,
      dayLabel: `${dayLabel} Dinner`,
      formattedDate,
      mealSlot: 'dinner',
      rotiCount: 4,
      rotiType: i === 3 ? 'bajra_bhakri' : 'ghee_phulka',
      gheeApplied: true,
      deliveryTimeSlot: '07:45 PM - 08:30 PM',
      status: isTodayDinnerPastCutoff ? 'in_preparation' : 'scheduled',
      cutoffTime: '06:30 PM',
      isPastCutoff: isTodayDinnerPastCutoff,
      specialInstructions: 'Double wrap butter paper',
    });
  }

  return schedule;
}

